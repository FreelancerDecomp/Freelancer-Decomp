# Freelancer Decomp: compiles RPGPU's HLSL shaders (src/RPGPU/shaders/*.hlsl) into SPIR-V,
# DXIL and MSL with SDL_shadercross and writes them into one C++ include,
# src/RPGPU/shaders/RpGpuShaderBytecode.generated.inc, which is committed (docs/re/rpgpu.md,
# "Shaders"). CI runs this and fails when the committed include differs.
#
#   pwsh tools/rpgpu_shaders.ps1 -ShaderCross <path to shadercross.exe>
#
# shadercross comes from vcpkg: the shader-tools feature of src/vcpkg.json, x64-windows.

param(
    [Parameter(Mandatory = $true)][string]$ShaderCross
)

$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $PSScriptRoot
$ShaderDir = Join-Path $Root 'src/RPGPU/shaders'
$Output = Join-Path $ShaderDir 'RpGpuShaderBytecode.generated.inc'
$Work = Join-Path ([System.IO.Path]::GetTempPath()) ('rpgpu-shaders-' + [System.Guid]::NewGuid())
New-Item -ItemType Directory -Force $Work | Out-Null

# shadercross needs dxcompiler.dll and dxil.dll next to it or on PATH (vcpkg's bin folder).
$env:PATH = (Join-Path (Split-Path -Parent (Split-Path -Parent (Split-Path -Parent $ShaderCross))) 'bin') + ';' + $env:PATH

function Format-Bytes([byte[]]$Bytes) {
    $Lines = New-Object System.Collections.Generic.List[string]
    for ($Index = 0; $Index -lt $Bytes.Length; $Index += 16) {
        $Count = [Math]::Min(16, $Bytes.Length - $Index)
        $Lines.Add('    ' + (($Bytes[$Index..($Index + $Count - 1)] | ForEach-Object { '0x{0:x2}' -f $_ }) -join ', ') + ',')
    }
    return ($Lines -join "`n")
}

$Sources = Get-ChildItem -Path $ShaderDir -Filter '*.hlsl' | Sort-Object Name
$Text = New-Object System.Text.StringBuilder
[void]$Text.AppendLine('// Generated by tools/rpgpu_shaders.ps1 from src/RPGPU/shaders/*.hlsl. Do not edit.')
[void]$Text.AppendLine('// Included once, by RpGpuShaders.cpp.')
[void]$Text.AppendLine('')
$Entries = New-Object System.Collections.Generic.List[string]
foreach ($Source in $Sources) {
    # name.vert.hlsl / name.frag.hlsl
    $Base = [System.IO.Path]::GetFileNameWithoutExtension($Source.Name)
    $Stage = if ($Base.EndsWith('.vert')) { 'vertex' } elseif ($Base.EndsWith('.frag')) { 'fragment' } else { throw "$($Source.Name): name must end in .vert.hlsl or .frag.hlsl" }
    $Symbol = ($Base -replace '[^A-Za-z0-9]', '_')
    $Blobs = @{}
    foreach ($Dest in @('SPIRV', 'DXIL', 'MSL')) {
        $Out = Join-Path $Work "$Symbol.$Dest"
        & $ShaderCross $Source.FullName -s HLSL -d $Dest -t $Stage -e main -o $Out
        if ($LASTEXITCODE -ne 0) { throw "shadercross failed for $($Source.Name) -> $Dest ($LASTEXITCODE)" }
        $Bytes = [System.IO.File]::ReadAllBytes($Out)
        if ($Dest -eq 'MSL') { $Bytes = $Bytes + [byte]0 } # MSL is source text: keep it terminated
        $Blobs[$Dest] = $Bytes
        [void]$Text.AppendLine("static const unsigned char k${Dest}_$Symbol[] = {")
        [void]$Text.AppendLine((Format-Bytes $Bytes))
        [void]$Text.AppendLine('};')
    }
    $Entries.Add("    {`"$Base`", kSPIRV_$Symbol, sizeof(kSPIRV_$Symbol), kDXIL_$Symbol, sizeof(kDXIL_$Symbol), kMSL_$Symbol, sizeof(kMSL_$Symbol) - 1},")
}
[void]$Text.AppendLine('')
[void]$Text.AppendLine('static const FRpGpuShaderBlob kRpGpuShaders[] = {')
foreach ($Entry in $Entries) { [void]$Text.AppendLine($Entry) }
[void]$Text.AppendLine('    {nullptr, nullptr, 0, nullptr, 0, nullptr, 0},')
[void]$Text.AppendLine('};')

# LF line endings, so the file is the same on every machine.
[System.IO.File]::WriteAllText($Output, ($Text.ToString() -replace "`r`n", "`n"))
Remove-Item -Recurse -Force $Work
Write-Host "Wrote $Output ($($Sources.Count) shaders)"
