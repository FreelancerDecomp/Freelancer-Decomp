"""Generate regress_client_slots.inl from src/include/rpc_iclient.h.

Every pure virtual of IClient becomes an override that records the call in the trace
(slot index and name) and returns a neutral value. Rerun after IClient changes:
    python src/FLRegress/gen_regress_client.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = os.path.join(HERE, "..", "include", "rpc_iclient.h")
OUTPUT = os.path.join(HERE, "regress_client_slots.inl")

# Neutral results. Startup (slot 10) must succeed or Server::Startup refuses to start.
RETURNS = {
    "Startup": "true",
    "Update": "0",
    "GetSendQSize": "0",
    "GetSendQBytes": "0",
    "GetLinkSaturation": "0.0",
}


def main() -> int:
    text = open(HEADER, encoding="utf-8").read()
    start = text.index("class RPC_ICLIENT_API IClient {")
    end = text.index("\n};", start)
    body = re.sub(r"//[^\n]*", "", text[start:end])
    decls = [re.sub(r"\s+", " ", d).strip() for d in re.findall(r"virtual[^;]*?=\s*0\s*;", body)]
    if len(decls) != 126:
        print(f"expected 126 IClient slots, found {len(decls)}", file=sys.stderr)
        return 1

    lines = [
        "// Generated by gen_regress_client.py from src/include/rpc_iclient.h. Do not edit.",
        "// Included inside class FRegressClient (regress_client.h).",
        "",
    ]
    for slot, decl in enumerate(decls):
        match = re.match(r"virtual (.+?)\b(\w+)\s*\((.*)\)\s*=\s*0\s*;$", decl)
        if not match:
            print(f"cannot parse slot {slot}: {decl}", file=sys.stderr)
            return 1
        ret, name, params = match.group(1).strip(), match.group(2), match.group(3)
        result = "" if ret == "void" else f" return {RETURNS[name]};"
        lines.append(f"{ret} {name}({params}) override {{ Record({slot}, \"{name}\");{result} }}")
    lines.append("")

    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as out:
        out.write("\n".join(lines))
    print(f"wrote {len(decls)} slots to {os.path.relpath(OUTPUT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
